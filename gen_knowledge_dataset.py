tok = AutoTokenizer.from_pretrained(MODEL)
model = AutoModelForCausalLM.from_pretrained(MODEL, torch_dtype=torch.float16).to(DEV).eval()

def norm(s):
    return re.sub(r"\s+", " ", s.lower()).strip()

def ask(q):
    msgs = [{"role": "user", "content": q}]
    ids = tok.apply_chat_template(msgs, tokenize=True, return_tensors="pt",
                                  add_generation_prompt=True).to(DEV)
    with torch.no_grad():
        out = model.generate(ids, max_new_tokens=MAX_NEW, do_sample=False)
    return tok.decode(out[0][ids.shape[1]:], skip_special_tokens=True)

def measure(fact):
    """hidden/энтропия/logprob на позиции t−1: ПЕРЕД ЗНАЧЕНИЕМ факта («X — |Y»)."""
    Y = fact.split(" — ", 1)[1]
    content = f"Факт: {fact}"
    msgs = [{"role": "user", "content": content}]
    ids = tok.apply_chat_template(msgs, tokenize=True, return_tensors="pt").to(DEV)
    content_ids = tok.encode(content)
    # Y после «— »: токенизируем с ведущим пробелом (хвост content_ids = « Y»)
    y_ids = tok.encode(" " + Y)
    assert content_ids[-len(y_ids):] == y_ids, f"хвост Y не совпал: {Y!r}"
    ct = torch.tensor(content_ids, device=DEV)
    start = -1
    for i in range(len(ids[0]) - len(ct) + 1):
        if torch.equal(ids[0][i:i+len(ct)], ct):
            start = i
            break
    assert start >= 0, "content не найден в шаблоне"
    pos_tm1 = start + len(content_ids) - len(y_ids) - 1   # позиция «—», предсказываем Y
    with torch.no_grad():
        out = model(ids, output_hidden_states=True)
        logits = out.logits[0, pos_tm1].float()
        hidden = out.hidden_states[-1][0, pos_tm1].float()
    p = torch.softmax(logits, dim=-1)
    entropy = -(p * torch.log(p + 1e-12)).sum().item()
    first_y_tok = content_ids[-len(y_ids)]
    logprob = torch.log_softmax(logits, dim=-1)[first_y_tok].item()
    return hidden.cpu(), entropy, logprob

def main():
    rows = []
    for group, cands in (("know", KNOW), ("notknow", NOTKNOW)):
        for fact, q, ans in cands:
            a = ask(q)
            ok = norm(ans) in norm(a)
            hid, ent, lp = measure(fact)
            label = 1 if ok else 0
            rows.append((fact, group, ok, hid, ent, lp, label))
            flag = "✓" if ok else "✗"
            print(f"[{group:7s}] {flag} label={label} | ent={ent:.3f} | lp={lp:.3f} | {fact[:58]}")
            if group == "know" and not ok:
                print(f"           ответ: {a[:80]!r}")

    print("\n=== Итоги (эмпирические лейблы) ===")
    n_know = sum(1 for r in rows if r[1] == "know")
    n_ok_know = sum(1 for r in rows if r[1] == "know" and r[6] == 1)
    n_nk = sum(1 for r in rows if r[1] == "notknow")
    n_ok_nk = sum(1 for r in rows if r[1] == "notknow" and r[6] == 0)
    print(f"know:    {n_ok_know}/{n_know} отвечены правильно")
    print(f"notknow: {n_ok_nk}/{n_nk} НЕ отвечены")
    print(f"(notknow, где модель ВСЁ ЖЕ ответила правильно — уходят в know: "
          f"эмпирика решила, что знание в весах)")

    keep = [r for r in rows if (r[1] == "know" and r[6] == 1) or (r[1] == "notknow" and r[6] == 0)]
    torch.save({
        "hidden": torch.stack([r[3] for r in keep]),
        "entropy": torch.tensor([r[4] for r in keep]),
        "logprob": torch.tensor([r[5] for r in keep]),
        "labels": torch.tensor([r[6] for r in keep]),
        "facts": [r[0] for r in keep],
        "groups": [r[1] for r in keep],
    }, os.path.join(os.path.dirname(__file__), "dataset_knowledge.pt"))
    print(f"\nСохранено: dataset_knowledge.pt, {len(keep)} примеров")

if __name__ == "__main__":
    main()
